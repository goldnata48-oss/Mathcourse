function makeIntroLesson(id, title, content, questions){
  return {
    id, module:1, title,
    html(lang){
      const text = content[lang];
      const points = text.points.map(point=>`<li>${point}</li>`).join("");
      return `
        <p>${text.lead}</p>
        <h3>${text.pointsTitle}</h3>
        <ul>${points}</ul>
        <h3>${text.practiceTitle}</h3>
        <div class="formula-box">${text.practice}</div>
        <div class="check-block">
          <h3>${text.checkTitle}</h3>
          <div id="mini-check"></div>
        </div>
      `;
    },
    mount(root, lang){
      renderMiniCheck(root.querySelector("#mini-check"), lang, questions);
    }
  };
}

/* ============================================================
   УРОКИ 8–9 КЛАССА: последовательности, уравнения, прикладные задачи.
   Форма повторяет makeIntroLesson, но допускает произвольное число
   блоков формул, примеров и строк списка — этого хватает для
   алгебраических тем, где важнее формулы, чем интерактивная схема.
   ============================================================ */
function makeTopicLesson(id, module, title, content, questions){
  return {
    id, module, title,
    html(lang){
      const t = content[lang];
      const points = (t.points||[]).map(point=>`<li>${point}</li>`).join("");
      const forms = (t.forms||[]).map(f=>`<div class="formula-box">${f}</div>`).join("");
      const examples = (t.examples||[]).map((ex, i)=>
        `<div class="example-box"><div class="ex-label">${i+1}</div><div class="ex-math">${ex}</div></div>`).join("");
      return `
        <p>${t.lead}</p>
        ${points ? `<h3>${t.pointsTitle}</h3><ul>${points}</ul>` : ""}
        ${forms ? `<h3>${t.formsTitle}</h3>${forms}` : ""}
        ${examples ? `<h3>${t.examplesTitle}</h3>${examples}` : ""}
        ${t.note ? `<p>${t.note}</p>` : ""}
        <div class="check-block">
          <h3>${t.checkTitle}</h3>
          <div id="mini-check"></div>
        </div>
      `;
    },
    mount(root, lang){
      renderMiniCheck(root.querySelector("#mini-check"), lang, questions);
    }
  };
}

function makeFinalQuestion(module, q, opts, explanation){
  const shift = (module + q.ru.length) % opts.length;
  return {
    module,
    q,
    opts:opts.slice(shift).concat(opts.slice(0,shift)),
    correct:(opts.length-shift)%opts.length,
    explanation
  };
}

